def normalize_unit(raw: str) -> str:
    """Каноническое имя единицы для ``raw``, либо исходное (в нижнем регистре), если неизвестно."""
    if not raw:
        return "шт"
    cleaned = raw.strip().lower()
    return _ALIASES.get(cleaned, cleaned)


def extract_unit_from_text(text: str) -> Optional[str]:
    """Пытается извлечь упоминание единицы измерения из текста (например '200 кг' → 'кг')."""
    if not text:
        return None
    text_lower = text.lower()
    # Сортируем по убыванию длины, чтобы длинные алиасы матчились раньше коротких
    for alias in sorted(_ALIASES, key=len, reverse=True):
        pattern = r"\b" + re.escape(alias) + r"\b"
        if re.search(pattern, text_lower):
            return _ALIASES[alias]
    return None


def unit_to_search_hint(unit: str, qty: float) -> str:
    """
    Возвращает строку-подсказку для поискового запроса, чтобы найти товар
    нужного количества/единицы.

    Примеры:
        'кг', 25  → '25 кг'
        'шт', 1   → ''          (подсказка не нужна, большинство товаров поштучно)
        'м', 100  → '100 м'
    """
    canonical = normalize_unit(unit)
    if canonical == "шт" and qty == 1:
        return ""
    if qty == int(qty):
        qty_str = str(int(qty))
    else:
        qty_str = f"{qty:.1f}"
    return f"{qty_str} {canonical}"
